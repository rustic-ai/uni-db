r"""Writes crates/uni-query-functions/src/java_regex/ucd_extra.rs.

Inputs:
  * the Unicode 15.0 UCD files PropList.txt and
    auxiliary/GraphemeBreakProperty.txt (https://www.unicode.org/Public/15.0.0/ucd/);
  * the output of ScanGraphemeClasses.java run on JDK 21 (a black-box scan of
    how `\X` classifies every code point through the public Pattern API).

The grapheme-cluster-break table starts from the UCD property and takes the
JDK's class wherever the scan disagrees (JDK 21 treats unassigned code points
other than reserved Extended_Pictographic ones as Control, except U+0378, and
U+11720..U+11721 as spacing marks).

    java ScanGraphemeClasses > scan.txt
    gen_ucd_extra.py --ucd DIR --scan scan.txt > .../ucd_extra.rs
"""
import argparse
import os

CODES = ["Other", "CR", "LF", "Control", "Extend", "ZWJ", "Regional_Indicator", "Prepend",
         "SpacingMark", "L", "V", "T", "LV", "LVT"]

SIG = {
    "0000000001": "Control", "0010000101": "Other", "0010000111": "Other",
    "0010001101": "Regional_Indicator", "0010110101": "T", "0011000101": "L|LV|LVT",
    "0011100101": "V", "0110000101": "Prepend", "1011111111": "Extend|ZWJ|SpacingMark",
}


def load(path, wanted=None):
    out = {}
    for line in open(path, encoding="utf-8"):
        line = line.split("#")[0].strip()
        if not line:
            continue
        r, v = [x.strip() for x in line.split(";")[:2]]
        if wanted and v not in wanted:
            continue
        a, b = (r.split("..") + [r])[:2] if ".." in r else (r, r)
        for c in range(int(a, 16), int(b, 16) + 1):
            out[c] = v
    return out


def ranges(pred):
    out, start = [], None
    for c in range(0x110001):
        inside = c <= 0x10FFFF and pred(c)
        if inside and start is None:
            start = c
        elif not inside and start is not None:
            out.append((start, c - 1))
            start = None
    return out


def merged(cls):
    if cls in ("CR", "LF", "Control"):
        return "Control"
    if cls in ("L", "LV", "LVT"):
        return "L|LV|LVT"
    if cls in ("Extend", "ZWJ", "SpacingMark"):
        return "Extend|ZWJ|SpacingMark"
    return cls


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ucd", required=True)
    ap.add_argument("--scan", required=True)
    args = ap.parse_args()
    gcb = load(os.path.join(args.ucd, "auxiliary", "GraphemeBreakProperty.txt"))
    props = load(os.path.join(args.ucd, "PropList.txt"),
                 {"White_Space", "Join_Control", "Noncharacter_Code_Point", "Hex_Digit"})
    table = [gcb.get(c, "Other") for c in range(0x110000)]
    for c in range(0xD800, 0xE000):
        table[c] = "Control"
    overrides = 0
    for line in open(args.scan, encoding="utf-8"):
        h, sig = line.split()
        c = int(h, 16)
        java = SIG[sig]
        if merged(table[c]) != java:
            overrides += 1
            table[c] = {"Extend|ZWJ|SpacingMark": "SpacingMark", "L|LV|LVT": "L"}.get(java, java)
    out = ["// SPDX-License-Identifier: Apache-2.0", "// Copyright 2024-2026 Dragonscale Team", "",
           "//! Unicode 15.0 data the JDK tables in `ucd_tables.rs` do not carry, generated by",
           "//! `scripts/java_regex_oracle/gen_ucd_extra.py` from PropList.txt,",
           "//! GraphemeBreakProperty.txt and a black-box scan of JDK 21's `\\X`",
           "//! (`ScanGraphemeClasses.java`; %d code points take the JDK's class). Do not edit." % overrides,
           ""]
    for name, prop in [("WHITE_SPACE", "White_Space"), ("JOIN_CONTROL", "Join_Control"),
                       ("NONCHARACTER", "Noncharacter_Code_Point"), ("HEX_DIGIT", "Hex_Digit")]:
        rs = ranges(lambda c, p=prop: props.get(c) == p)
        out.append("/// UCD `%s`." % prop)
        out.append("pub(crate) const %s: &[(u32, u32)] = &[" % name)
        out.extend("    (0x%X, 0x%X)," % r for r in rs)
        out.append("];")
        out.append("")
    out.append("/// Grapheme_Cluster_Break as JDK 21's `\\X` applies it, by range; absent code")
    out.append("/// points are `Other`. Values index `GCB_NAMES`.")
    out.append("pub(crate) const GCB: &[(u32, u32, u8)] = &[")
    start = 0
    for c in range(1, 0x110001):
        if c == 0x110000 or table[c] != table[start]:
            if table[start] != "Other":
                out.append("    (0x%X, 0x%X, %d)," % (start, c - 1, CODES.index(table[start])))
            start = c
    out.append("];")
    out.append("")
    out.append("/// Names of the `GCB` values.")
    out.append("#[allow(dead_code)]")
    out.append("pub(crate) const GCB_NAMES: &[&str] = &[%s];" % ", ".join('"%s"' % n for n in CODES))
    print("\n".join(out))


if __name__ == "__main__":
    main()
